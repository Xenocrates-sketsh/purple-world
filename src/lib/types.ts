import type { Timestamp } from "firebase/firestore";

export type Role = "teacher" | "student";

export type AttendanceStatus = "present" | "absent" | "late" | "excused";
export type AssessmentType =
  | "exercise"
  | "test"
  | "homework"
  | "quiz"
  | "exam"
  | "other";
export type ExerciseCategory =
  | "grammar"
  | "vocabulary"
  | "reading"
  | "writing"
  | "listening"
  | "bac_preparation"
  | "mixed";
export type ExerciseDifficulty = "easy" | "medium" | "hard";
export type SubmissionStatus = "submitted" | "late" | "graded";
export type AnnouncementType =
  | "new_lesson"
  | "schedule_change"
  | "new_exercise"
  | "exam_reminder"
  | "payment_reminder"
  | "general"
  | "bac_info";
export type AnnouncementTarget = "all" | "group" | "student";
export type PaymentStatus = "paid" | "due";
export type NotificationType =
  | "message"
  | "new_exercise"
  | "new_announcement"
  | "new_lesson"
  | "upcoming_lesson"
  | "payment_due"
  | "new_grade"
  | "schedule_change";

/** A student's request to join the academy (created from the no-password login form). */
export type ArrivalStatus = "pending" | "accepted" | "rejected";

/** arrivals/{arrivalId} — student requests approval to join via name + email. */
export interface ArrivalDoc {
  name: string;
  email: string;
  school: string | null;
  /** student number or phone, free-form */
  number: string | null;
  age: number | null;
  status: ArrivalStatus;
  /** the (anonymous) auth uid that submitted this request */
  uid: string | null;
  /** set when accepted */
  studentId: string | null;
  createdAt: Timestamp;
  handledAt: Timestamp | null;
  handledBy: string | null;
}

/** users/{uid} */
export interface UserDoc {
  role: Role;
  email: string;
  displayName: string;
  avatarUrl: string | null;
  /** Preset fruit/veg avatar key (students) — renders an emoji, uses no storage. */
  avatarKey: string | null;
  /** Present for students; links to students/{studentId} */
  studentId: string | null;
  /** Present for students; denormalized from their student doc for rule simplicity */
  groupId: string | null;
  /** Teacher-set lockout flag — blocked students are barred from the app and from chat */
  blocked?: boolean;
  /** studentId as stored on the students doc (inverse link) */
  createdAt: Timestamp;
  prefs?: {
    notifications: boolean;
    language: string;
  };
}

/** students/{studentId} */
export interface StudentDoc {
  name: string;
  studentNo: string;
  email: string | null;
  age: number | null;
  phone: string | null;
  parentPhone: string | null;
  school: string | null;
  stream: string | null;
  groupId: string | null;
  active: boolean;
  /** Teacher-set lockout flag — blocked students can't use the app or chat */
  blocked: boolean;
  bacInfo: {
    year: string | null;
    targetScore: number | null;
  };
  avatarUrl: string | null;
  /** Preset fruit/veg avatar key (students) — renders an emoji, uses no storage. */
  avatarKey: string | null;
  /** Stamp set when the student claims the record via the invite flow */
  registeredAt: Timestamp | null;
  createdAt: Timestamp;
  /** Set once a student claims this record via the invite flow */
  linkedUid: string | null;
  /** Latest sign-up invite code generated by the teacher for this student */
  inviteCode: string | null;
}

/** A weekly recurring slot on a group */
export interface ScheduleSlot {
  day: 0 | 1 | 2 | 3 | 4 | 5 | 6;
  startTime: string; // "17:00"
  endTime: string; // "18:30"
  location: string | null;
  durationMin: number;
}

/** groups/{groupId} */
export interface GroupDoc {
  name: string;
  description: string | null;
  color: string;
  scheduleSlots: ScheduleSlot[];
  createdAt: Timestamp;
}

/** lessons/{lessonId} — a dated concrete session */
export interface LessonDoc {
  groupId: string;
  title: string;
  startsAt: Timestamp;
  durationMin: number;
  location: string | null;
  notes: string | null;
  createdAt: Timestamp;
}

/** lessons/{lessonId}/attendance/{studentId} */
export interface AttendanceDoc {
  status: AttendanceStatus;
  markedAt: Timestamp;
}

/** payments/{paymentId} */
export interface PaymentDoc {
  studentId: string;
  amount: number | null;
  dueDate: Timestamp;
  paidDate: Timestamp | null;
  /** `paid` or `due`. Overdue is DERIVED (due + dueDate < now) — never stored stale. */
  status: PaymentStatus;
  notes: string | null;
  createdAt: Timestamp;
}

/** assessments/{assessmentId} */
export interface AssessmentDoc {
  title: string;
  type: AssessmentType;
  groupId: string | null;
  date: Timestamp;
  maxScore: number;
  description: string | null;
  createdAt: Timestamp;
}

/** assessments/{assessmentId}/results/{studentId} */
export interface AssessmentResultDoc {
  assessmentId: string;
  score: number;
  feedback: string | null;
  createdAt: Timestamp;
}

/** exercises/{exerciseId} */
export interface ExerciseDoc {
  title: string;
  description: string | null;
  instructions: string | null;
  category: ExerciseCategory;
  difficulty: ExerciseDifficulty;
  deadline: Timestamp | null;
  assignedGroupIds: string[];
  assignedStudentIds: string[];
  attachmentUrls: string[];
  archived: boolean;
  createdAt: Timestamp;
}

/** exercises/{exerciseId}/submissions/{studentId} */
export interface SubmissionDoc {
  content: string | null;
  attachmentUrl: string | null;
  submittedAt: Timestamp;
  status: SubmissionStatus;
  grade: number | null;
  feedback: string | null;
  gradedAt: Timestamp | null;
}

/** announcements/{announcementId} */
export interface AnnouncementDoc {
  title: string;
  body: string;
  type: AnnouncementType;
  target: AnnouncementTarget;
  groupId: string | null;
  studentId: string | null;
  /** Derived for querying, e.g. ["all", "group:abc", "student:xyz"] */
  recipientKeys: string[];
  createdAt: Timestamp;
}

/** programUnits/{unitId} */
export interface ProgramUnitDoc {
  title: string;
  description: string | null;
  order: number;
  createdAt: Timestamp;
}

/** programUnits/{unitId}/lessons/{lessonId} */
export interface ProgramLessonDoc {
  title: string;
  order: number;
  /** Uploaded PDFs/images/office docs attached to the lesson. */
  attachmentUrls: string[];
  /**
   * Group IDs allowed to see this lesson. Empty array = all groups.
   * Students only read lessons whose assignedGroupIds is empty OR contains
   * their own groupId.
   */
  assignedGroupIds: string[];
  createdAt: Timestamp;
}

/** conversations/{conversationId} */
export interface ConversationDoc {
  /** "direct" = teacher + one student, "group" = teacher + a class group */
  kind: "direct" | "group";
  participantIds: string[];
  /** the students/{id} this conversation belongs to (direct chats) */
  studentId: string | null;
  /** the groups/{id} this conversation belongs to (group chats) */
  groupId: string | null;
  /** display name for group chats (denormalized from the group) */
  name: string | null;
  teacherId: string;
  createdAt: Timestamp;
  lastMessageAt: Timestamp | null;
  lastMessagePreview: string | null;
  /** denormalized so unread can be computed from the conversation list */
  lastMessageSenderId: string | null;
}

/** conversations/{conversationId}/messages/{messageId} */
export interface MessageDoc {
  senderId: string;
  text: string;
  createdAt: Timestamp;
  /** uids that have seen this message (starts as [senderId]) */
  readBy: string[];
  /** client-generated id used to reconcile optimistic sends */
  clientId: string | null;
  /** set when the sender edits the message */
  editedAt: Timestamp | null;
  /** soft-delete marker; text is kept for history but hidden in the UI */
  deletedAt: Timestamp | null;
  /** uid -> emoji reactions (one per user per message) */
  reactions: Record<string, string> | null;
}

/** conversations/{conversationId}/participants/{uid} */
export interface ParticipantDoc {
  uid: string;
  conversationId: string;
  lastReadAt: Timestamp;
  /** transient "currently typing" heartbeat; compared against the clock */
  typingAt: Timestamp | null;
  /**
   * Messenger-style nicknames: maps another participant's uid -> the label the
   * owner wants to see for them in THIS conversation only. Each side sets its
   * own view (stored on its own participant marker), so it's private.
   */
  nicknames: Record<string, string> | null;
}

/** notifications/{uid}/items/{notificationId} */
export interface NotificationDoc {
  type: NotificationType;
  title: string;
  body: string | null;
  link: string | null;
  read: boolean;
  createdAt: Timestamp;
}

/** notes/{studentId}/entries/{entryId} */
export interface NoteEntryDoc {
  content: string;
  createdAt: Timestamp;
  updatedAt: Timestamp;
}

/** invites/{code} */
export interface InviteDoc {
  studentId: string;
  email: string | null;
  used: boolean;
  expiresAt: Timestamp;
  createdAt: Timestamp;
}

/** Firestore document timestamps serialize to {seconds, nanoseconds} client-side. */
export type FireTime = Timestamp;